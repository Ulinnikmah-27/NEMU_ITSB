CREATE TABLE IF NOT EXISTS ukm (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT NOT NULL UNIQUE, nama TEXT NOT NULL,
 kategori TEXT NOT NULL, profil TEXT NOT NULL CHECK(jsonb_typeof(profil::jsonb)='object'),
 aktif INTEGER NOT NULL DEFAULT 1, updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','mahasiswa','pengurus')),
 nama TEXT NOT NULL, nim TEXT UNIQUE, prodi TEXT NOT NULL DEFAULT '', angkatan TEXT NOT NULL DEFAULT '',
 ukm_id BIGINT REFERENCES ukm(id) ON DELETE RESTRICT,
 aktif INTEGER NOT NULL DEFAULT 1 CHECK(aktif IN (0,1)), created_at TEXT NOT NULL,
 CHECK(role != 'pengurus' OR ukm_id IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL CHECK(value::jsonb IS NOT NULL));
CREATE TABLE IF NOT EXISTS kuesioner (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 versi TEXT NOT NULL, jawaban TEXT NOT NULL CHECK(jsonb_typeof(jawaban::jsonb)='object'), created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS rekomendasi (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 kuesioner_id BIGINT NOT NULL REFERENCES kuesioner(id),
 bobot TEXT NOT NULL, hasil TEXT NOT NULL CHECK(jsonb_typeof(hasil::jsonb)='array'), created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS pendaftaran (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 ukm_id BIGINT NOT NULL REFERENCES ukm(id), periode TEXT NOT NULL,
 rekomendasi_id BIGINT NOT NULL REFERENCES rekomendasi(id), skor DOUBLE PRECISION NOT NULL CHECK(skor>=0 AND skor<=100),
 status TEXT NOT NULL DEFAULT 'Menunggu' CHECK(status IN ('Menunggu','Diterima','Ditolak','Dibatalkan')),
 konfirmasi TEXT NOT NULL DEFAULT 'Belum' CHECK(konfirmasi IN ('Belum','Diambil','Dilepas')),
 catatan TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
 UNIQUE(user_id,ukm_id,periode)
);
CREATE TABLE IF NOT EXISTS hasil_seleksi (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pendaftaran_id BIGINT NOT NULL REFERENCES pendaftaran(id),
 actor_id BIGINT NOT NULL REFERENCES users(id), status TEXT NOT NULL,
 catatan TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS assets (key TEXT PRIMARY KEY, data BYTEA NOT NULL, mime TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS login_attempts (username TEXT PRIMARY KEY, attempts INTEGER NOT NULL, locked_until DOUBLE PRECISION NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS idx_kuesioner_user ON kuesioner(user_id,id);
CREATE INDEX IF NOT EXISTS idx_rekomendasi_user ON rekomendasi(user_id,id);
CREATE INDEX IF NOT EXISTS idx_pendaftaran_ukm ON pendaftaran(ukm_id,periode,status);

CREATE UNIQUE INDEX users_username_lower ON users(lower(username));
CREATE OR REPLACE FUNCTION nemu.check_two_choices() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status='Dibatalkan' THEN RETURN NEW; END IF;
 PERFORM id FROM nemu.users WHERE id=NEW.user_id FOR UPDATE;
 IF (SELECT count(*) FROM nemu.pendaftaran WHERE user_id=NEW.user_id AND periode=NEW.periode AND status!='Dibatalkan' AND id IS DISTINCT FROM NEW.id)>=2 THEN
  RAISE EXCEPTION 'Maksimal dua UKM per periode' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER max_two_choices BEFORE INSERT OR UPDATE OF status ON pendaftaran FOR EACH ROW EXECUTE FUNCTION nemu.check_two_choices();
